#!/usr/bin/env python3
"""Chart Scanner for trader-scanner: scan thousands of charts for setups. Standard library only.

    python3 scan.py universe                          # NSE's equity list (series EQ) -> trader/universe.txt
    python3 scan.py universe --index nifty500         # or an index: nifty50, nifty100, nifty200, nifty500 ...
    python3 scan.py daily                             # before the open: daily setups -> trader/watchlist.json
    python3 scan.py daily --symbols RELIANCE,TCS,INFY # or --watchlist FILE, or --limit 200
    python3 scan.py orb                               # after 9:35 AM IST: opening-range breakouts so far
    python3 scan.py orb --at 09:50 --or-minutes 15    # cut the clock at 9:50 AM IST
    python3 scan.py orb --offline RELIANCE.json --now "2026-11-06 09:50"

Tickers are NSE trading symbols (RELIANCE, M&M, BAJAJ-AUTO); Yahoo reads
them as RELIANCE.NS. BSE:X reads the BSE listing (X.BO).

universe  Downloads NSE's list of listed equities (EQUITY_L.csv from
          nsearchives.nseindia.com) and keeps the EQ series: the shares that
          trade normally and can be bought intraday. BE (trade-for-trade, no
          intraday) and the rest are dropped; --series EQ,BE keeps BE too.
          --index NAME uses an index's constituents instead (NSE's
          ind_<index>list.csv): nifty50, nifty100, nifty200, nifty500,
          midcap150, smallcap250, next50. A smaller, more liquid list scans
          faster and gives day-trade-able charts; nifty500 is a good start.
          NSE's archive wants a browser-like User-Agent, which this sends.

daily     Pre-market scan of daily CLOSES (Yahoo spark: 20 symbols a request,
          3 months of 1-day bars, closes only). Liquidity from the spark meta:
          regularMarketPrice >= --min-price (₹50) and regularMarketVolume >=
          --min-volume (2,00,000 shares). Setups, from closes only:
            breakout_20d     the last close is above every close of the 20 before it
            bull_flag        up more than 10 % over the 10 sessions before the
                             last 5, then the last 5 closes inside a 5 % range
            reclaim_ma20     closed under the 20-day average, then closed above it
            oversold         RSI 14 (Wilder) under 30
            oversold_bounce  RSI 14 was under 30 yesterday and today closed up
          Today's daily bar is dropped until the session's close.

orb       Opening-range breakouts, 5-minute bars. The range is the first
          --or-minutes (15) of the session. Stage 1: spark closes for every
          symbol (1 day of 5-minute bars, 20 a request); a chart goes on only
          if a completed bar after the range closed at or above the highest
          close of the range (a necessary condition). Stage 2: each candidate's
          v8 chart (real highs and lows): range high = the highest high of the
          range bars, a hit = the first completed bar to CLOSE above it, at that
          bar's close time. Stage 2 fetches at most --max-confirm (200) charts,
          the most traded candidates first (price x volume so far), and says
          so when it stops short. A chart is usable only when every 5-minute
          bar from 9:15 to the cutoff is there (a missing bar is a halt, a
          circuit lock or no trades). Floors: --min-price 50 (last close),
          --min-volume 0. A cutoff after no_entries_after (14:45) is refused:
          a breakout found then is too late for a day trade.

Bars: null closes are dropped, a bar off the 5-minute grid (the live tick,
like 10:49:45) is dropped, and a bar counts only once it is complete
(start + 5 minutes <= the clock). Times are IST. --now pins the clock
("2026-11-06 09:50", IST; ...Z for UTC). F&O stocks stop continuous trading
at 3:15 PM for the closing auction, so their last 5-minute bar is 3:10.

Yahoo's endpoints are free, unofficial and can lag. query2 first, query1 on
a 429 or 5xx, one retry after a pause on a 429. A polite pause between
requests (--pause). Partial results are reported as partial.

--offline PATH reads files instead of the network: universe wants a folder
with EQUITY_L.csv (or ind_<index>list.csv); daily and orb take a folder of
<T>.json files or spark responses, or one file that is a spark response, a
v8 chart, Kite candles (get_historical_data output, with "symbol" set), or a
bundle {"RELIANCE": <v8 json or Kite candles>, ...}. .json.gz is fine.

A scan is a list of charts that match a rule, not a list of stocks to buy.
Exit code 0 when the scan found something, 1 when it did not or could not run.
"""

