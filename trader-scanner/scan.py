def to_ist(utc):
    """Naive UTC -> naive IST. India is UTC+5:30 all year (no daylight saving)."""
    return utc.replace(tzinfo=None) + IST


def ist_to_utc(local):
    """Naive IST -> naive UTC."""
    return local - IST


def ts_to_ist(ts):
    """Unix seconds -> naive IST. Never uses the machine's time zone."""
    return to_ist(datetime.datetime(1970, 1, 1) + datetime.timedelta(seconds=int(ts)))


def parse_now(text):
    """ISO time -> naive UTC. A time without an offset is taken as IST."""
    if not text:
        return datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0, tzinfo=None)
    t = text.strip().replace("Z", "+00:00")
    try:
        dt = datetime.datetime.fromisoformat(t)
    except ValueError:
        raise ScanError('--now wants a time like "2026-11-06 09:50" (IST) or ...Z (UTC)')
    if dt.tzinfo is None:
        return ist_to_utc(dt)
    return (dt - dt.utcoffset()).replace(tzinfo=None)


def parse_hhmm(text, flag="--at"):
    m = re.match(r"^\s*(\d{1,2}):(\d{2})\s*$", text or "")
    if not m or int(m.group(1)) > 23 or int(m.group(2)) > 59:
        raise ScanError("%s wants an IST time like 09:50" % flag)
    return datetime.time(int(m.group(1)), int(m.group(2)))


def _clock_of(text):
    h, m = str(text).split(":")
    return datetime.time(int(h), int(m))


def special(d):
    """The name of a special session (Muhurat trading) on this date, or None."""
    sp = NSE_SPECIAL.get(d.isoformat())
    return sp[2] if sp else None


def trading_day(d):
    """(is_trading_day, reason). Weekends and the NSE holiday list; a special
    session (Muhurat trading) opens a day that is otherwise closed."""
    if d.isoformat() in NSE_SPECIAL:
        return True, ""
    if d.weekday() >= 5:
        return False, "weekend"
    name = NSE_HOLIDAYS.get(d.isoformat())
    if name:
        return False, "NSE holiday: " + name
    return True, ""


def session(d):
    """(open_time, close_time) in IST, or None if closed all day. The close is
    3:30 PM; F&O stocks stop continuous trading at 3:15 PM (CAS_END)."""
    sp = NSE_SPECIAL.get(d.isoformat())
    if sp:
        return _clock_of(sp[0]), _clock_of(sp[1])
    ok, _ = trading_day(d)
    if not ok:
        return None
    return OPEN, CLOSE


def clock_label(t):
    """datetime or time -> '9:50 AM'."""
    h = t.hour % 12 or 12
    return "%d:%02d %s" % (h, t.minute, "AM" if t.hour < 12 else "PM")


def day_label(d):
    return "%s %s" % (d.strftime("%a"), d.isoformat())


