def http_get(url, timeout=20):
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "*/*"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read().decode("utf-8", "replace")


def yahoo_get(path):
    """GET a Yahoo Finance path. query2 first, query1 on a 429 or 5xx, and one
    more round after BACKOFF seconds if a 429 was seen. 4xx other than 429 is final."""
    last = "no answer"
    for attempt in (0, 1):
        saw_429 = False
        for host in YAHOO_HOSTS:
            try:
                return http_get(host + path)
            except urllib.error.HTTPError as e:
                last = "HTTP %d" % e.code
                try:
                    body = e.read().decode("utf-8", "replace") if 400 <= e.code < 500 and e.code != 429 else ""
                except Exception:
                    body = ""
                finally:
                    e.close()
                if e.code == 429:
                    saw_429 = True
                    continue
                if e.code >= 500:
                    continue
                if body.strip().startswith("{"):
                    return body  # Yahoo's JSON error ("No data found"), parsed by the caller
                raise ScanError("Yahoo answered %s for %s" % (last, path.split("?")[0]))
            except (urllib.error.URLError, OSError) as e:
                last = str(getattr(e, "reason", e))
                continue
        if attempt == 0 and saw_429:
            SLEEP(BACKOFF)
            continue
        break
    raise ScanError("Yahoo answered %s for %s" % (last, path.split("?")[0]))


def plain_symbol(sym):
    """The ticker as the pack writes it: an NSE trading symbol ("RELIANCE"), or
    "BSE:X" for a BSE listing. "NSE:RELIANCE" and "RELIANCE.NS" -> "RELIANCE";
    "X.BO" -> "BSE:X"."""
    s = str(sym or "").strip().upper()
    if s.startswith("NSE:"):
        s = s[4:]
    if s.endswith(".NS"):
        s = s[:-3]
    if s.endswith(".BO"):
        s = "BSE:" + s[:-3]
    return s


def yahoo_symbol(sym):
    """RELIANCE -> RELIANCE.NS, BSE:500325 -> 500325.BO; an index (^NSEI) stays."""
    s = plain_symbol(sym)
    if s.startswith("^"):
        return s
    if s.startswith("BSE:"):
        return s[4:] + ".BO"
    return s + ".NS"


def yahoo_quoted(sym):
    """The Yahoo symbol, escaped for a URL path (M&M.NS -> M%26M.NS)."""
    return urllib.parse.quote(yahoo_symbol(sym), safe=".-^")


KITE_INTERVALS = {"minute": "1m", "3minute": "3m", "5minute": "5m", "10minute": "10m", "15minute": "15m",
                  "30minute": "30m", "60minute": "60m", "day": "1d"}


def _kite_ts(value):
    """A Kite candle time ("2026-11-06T09:15:00+05:30", or a datetime string
    without an offset, read as IST) -> Unix seconds."""
    t = str(value).strip().replace("Z", "+00:00").replace(" ", "T", 1)
    if re.search(r"[+-]\d{4}$", t):
        t = t[:-2] + ":" + t[-2:]
    dt = datetime.datetime.fromisoformat(t)
    if dt.tzinfo is None:
        dt = dt - IST
    else:
        dt = (dt - dt.utcoffset()).replace(tzinfo=None)
    return int((dt - datetime.datetime(1970, 1, 1)).total_seconds())


def kite_candles(doc):
    """(candles, symbol, interval, fetched_at) if doc is Kite historical data, else None.
    Kite comes as the connector's list of {date, open, high, low, close, volume},
    as {"symbol": ..., "interval": ..., "candles": [...]} (what this pack saves),
    or as the REST answer {"data": {"candles": [[time, o, h, l, c, v], ...]}}.
    "fetched_at" (ISO time) says when it was read: the last candle may still
    have been forming then."""
    sym = interval = as_of = None
    if isinstance(doc, dict):
        sym, interval = doc.get("symbol") or doc.get("tradingsymbol"), doc.get("interval")
        as_of = doc.get("fetched_at")
        if isinstance(doc.get("data"), dict):
            doc = doc["data"]
        doc = doc.get("candles") if isinstance(doc, dict) else None
    if not isinstance(doc, list) or (doc and not isinstance(doc[0], (dict, list))):
        return None
    out = []
    for c in doc:
        if isinstance(c, dict):
            if "date" not in c or "close" not in c:
                return None
            row = (c["date"], c.get("open"), c.get("high"), c.get("low"), c["close"], c.get("volume"))
        else:
            row = tuple(c[:6]) + (None,) * (6 - len(c[:6]))
        out.append(row)
    return out, sym, interval, as_of


def chart_from_kite(candles, sym, interval=None, as_of=None):
    """Kite candles -> the Yahoo chart JSON shape, so every reader takes either.
    The data time is fetched_at when given, else the last candle's close."""
    ts, o, h, l, c, v = [], [], [], [], [], []
    for row in candles:
        ts.append(_kite_ts(row[0]))
        o.append(row[1])
        h.append(row[2])
        l.append(row[3])
        c.append(row[4])
        v.append(row[5] or 0)
    order = sorted(range(len(ts)), key=lambda i: ts[i])
    pick = lambda arr: [arr[i] for i in order]
    ts, o, h, l, c, v = map(pick, (ts, o, h, l, c, v))
    gran = KITE_INTERVALS.get(str(interval or ""), interval)
    if not gran and len(ts) > 1:
        gaps = [b - a for a, b in zip(ts, ts[1:]) if 0 < b - a < 3600]
        gran = {60: "1m", 300: "5m", 900: "15m"}.get(min(gaps)) if gaps else None
    step = {"1m": 60, "3m": 180, "5m": 300, "10m": 600, "15m": 900, "30m": 1800, "60m": 3600}.get(gran, 0)
    meta = {"symbol": yahoo_symbol(sym), "currency": "INR", "dataGranularity": gran,
            "regularMarketTime": _kite_ts(as_of) if as_of else ((ts[-1] + step) if ts else None),
            "regularMarketPrice": c[-1] if c else None, "source": "kite"}
    return {"chart": {"result": [{"meta": meta, "timestamp": ts,
                                  "indicators": {"quote": [{"open": o, "high": h, "low": l,
                                                            "close": c, "volume": v}]}}],
                      "error": None}}


